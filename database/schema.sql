-- ---------------------------------------------------------------------
-- Indices unicos (antes en migraciones/001_indices_unicos.sql).
-- La sincronizacion con APIs externas y la importacion de JSON buscan por id_externo
-- antes de insertar; estos indices garantizan que nunca se dupliquen registros.
-- ---------------------------------------------------------------------

-- id_externo es unico dentro de su "padre" (una temporada puede repetir numeros de otra)
CREATE UNIQUE INDEX ux_evento_temporada_externo ON evento(id_temporada, id_externo) WHERE id_externo IS NOT NULL;
CREATE UNIQUE INDEX ux_sesion_evento_externo ON sesion(id_evento, id_externo) WHERE id_externo IS NOT NULL;
CREATE UNIQUE INDEX ux_etapa_evento_externo ON etapa(id_evento, id_externo) WHERE id_externo IS NOT NULL;

-- Pilotos y equipos son globales: el id_externo lleva prefijo de categoria (ej: "F1:max_verstappen")
CREATE UNIQUE INDEX ux_piloto_externo ON piloto(id_externo) WHERE id_externo IS NOT NULL;
CREATE UNIQUE INDEX ux_equipo_externo ON equipo(id_externo) WHERE id_externo IS NOT NULL;

-- Una temporada por categoria y anio
CREATE UNIQUE INDEX ux_temporada_categoria_anio ON temporada(id_categoria, anio);

-- Un solo resultado por piloto en cada sesion, y por tripulacion en cada etapa
CREATE UNIQUE INDEX ux_resultado_sesion_piloto ON resultado_sesion(id_sesion, id_piloto);
CREATE UNIQUE INDEX ux_resultado_etapa_tripulacion ON resultado_etapa(id_etapa, id_tripulacion);

-- Email de usuario unico (login, sin distinguir mayusculas)
CREATE UNIQUE INDEX ux_usuario_email ON usuario(lower(email));

CREATE OR REPLACE FUNCTION actualizar_fecha_actualizacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW."fechaActualizacion" = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_usuario_fecha_actualizacion
BEFORE UPDATE ON usuario
FOR EACH ROW EXECUTE FUNCTION actualizar_fecha_actualizacion();

